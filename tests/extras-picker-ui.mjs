import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const source = readFileSync(new URL('../wp-plugin/mathlin-booking/admin/extras-picker.js', import.meta.url), 'utf8');
const field = value => ({value, events: {}, addEventListener(k, fn) {this.events[k] = fn;}, setCustomValidity(v) {this.error = v;}});
const picker = field('');
const elements = {catalogue_quantity: field('1'), catalogue_version: field(''), amount: field('12.34'), description: field('Custom extra'), category: field('other')};
picker.closest = () => ({elements});
const status = {};
vm.runInNewContext(source, {document: {getElementById: id => id === 'mbs-extra-picker' ? picker : status}, MBS_Extras: {items: [{id: 'synthetic', version: 4, description: 'Cleaning', unit: 'visit', category: 'cleaning', unit_amount_minor: 2500}]}});
assert.equal(elements.catalogue_quantity.disabled, true);
picker.value = 'synthetic'; picker.events.change();
assert.equal(elements.catalogue_version.value, '4');
assert.equal(elements.amount.value, '25.00');
assert.equal(elements.description.readOnly, true);
assert.equal(elements.category.disabled, true);
elements.catalogue_quantity.value = '3'; elements.catalogue_quantity.events.input();
assert.equal(elements.amount.value, '75.00');
assert.equal(elements.description.value, 'Cleaning (3 × visit)');
elements.catalogue_quantity.value = '1.5'; elements.catalogue_quantity.events.input();
assert.ok(elements.catalogue_quantity.error);
picker.value = ''; picker.events.change();
assert.equal(elements.catalogue_quantity.error, '');
assert.equal(elements.amount.value, '12.34');
assert.equal(elements.description.value, 'Custom extra');
assert.equal(elements.amount.readOnly, false);
assert.equal(elements.category.disabled, false);
assert.equal(elements.catalogue_version.value, '');
assert.equal(elements.category.value, 'other');
console.log('EXTRAS_PICKER_UI_OK (15 checks)');
